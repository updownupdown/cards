// Builds the shared data for the design overhaul mockups (data.js) and the
// small copies of the game art they show (art/).
//
//   node docs/design-overhauls/build.mjs <games snapshot> <art checkout>
//
// <games snapshot> is docs/gallery-mockups/games.js from the gallery mockups
// branch (map positions, links and rewards); <art checkout> holds
// assets/thumbnails-full and src/data/games from the new cover art branch.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";
import sharp from "sharp";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const [snapshot, artRoot] = process.argv.slice(2);
const read = (path) => readFileSync(path, "utf8");

const ctx = { window: {} };
vm.runInNewContext(read(snapshot), ctx);
const games = ctx.window.GAMES;

// The new art's credits and colours.
for (const game of games) {
  const file = join(artRoot, "src/data/games", game.path.slice(1) + ".ts");
  let src;
  try {
    src = read(file);
  } catch {
    continue;
  }
  const credit = src.slice(src.indexOf("thumbnailCredit"));
  const field = (name, from = credit) =>
    from.match(new RegExp(`${name}:\\s*"([^"]*)"`))?.[1];
  game.art = {
    title: field("title") ?? game.art.title,
    artist: field("artistName") ?? game.art.artist,
    date: field("date") ?? game.art.date,
    source: field("sourceName") ?? game.art.source,
  };
  game.dark = field("gameColorDark", src) ?? game.dark;
  game.pale = field("gameColorPale", src) ?? game.pale;
}

const quotesSource = read(join(root, "src/components/Collectibles/QuotesText.ts"));
const quotes = [
  ...quotesSource.matchAll(
    /text: `([\s\S]*?)`,\s*author: `([\s\S]*?)`,\s*source: `([\s\S]*?)`/g,
  ),
].map(([, text, author, source]) => ({ text, author, source }));

const authorsSource = read(join(root, "src/data/quote-authors.generated.ts"));
const authors = [
  ...authorsSource.matchAll(
    /name: "(.*?)",\s*born: (-?\d+),\s*died: (-?\d+|null),\s*circa: (true|false),\s*portrait: "(.*?)"/g,
  ),
].map(([, name, born, died, circa, portrait]) => ({
  name: JSON.parse(`"${name}"`),
  born: Number(born),
  died: died === "null" ? null : Number(died),
  circa: circa === "true",
  portrait,
}));

const taoSource = read(join(root, "src/components/Collectibles/TaoText.ts"));
const tao = [
  ...taoSource.matchAll(/chapter: (\d+),\s*text: `([\s\S]*?)`/g),
].map(([, chapter, text]) => ({ chapter: Number(chapter), text }));

const figuresSource = read(join(root, "src/data/tao-constellations.ts"));
const start = figuresSource.indexOf("const figures: Figure[] = [");
const end = figuresSource.indexOf("\n];", start);
const figures = vm.runInNewContext(
  figuresSource.slice(start + "const figures: Figure[] = ".length, end + 2),
);
tao.forEach((chapter, i) => (chapter.figure = figures[i]));

const artOut = join(here, "art");
mkdirSync(artOut, { recursive: true });
const full = join(artRoot, "assets/thumbnails-full");
for (const file of readdirSync(full)) {
  await sharp(join(full, file))
    .resize(520, 520, { fit: "inside" })
    .webp({ quality: 68 })
    .toFile(join(artOut, file))
    .then(({ width, height }) =>
      games
        .filter((g) => g.thumb === file)
        .forEach((g) => Object.assign(g, { w: width, h: height })),
    );
}
writeFileSync(
  join(here, "data.js"),
  "// Generated by build.mjs.\nwindow.DATA = " +
    JSON.stringify({ games, quotes, authors, tao }) +
    ";\n",
);

console.log(
  `${games.length} games, ${quotes.length} quotes, ${authors.length} authors, ${tao.length} chapters`,
);
